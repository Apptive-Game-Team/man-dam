def overlaps(a: str, b: str) -> bool:
    """두 주제가 겹치는가. "헬스장" 과 "헬스장 등록" 은 겹친다."""
    a, b = a.replace(" ", ""), b.replace(" ", "")
    return bool(a) and bool(b) and (a in b or b in a)


SHOWN = 3  # 한 번에 보여줄 예시 수


def as_prompt(topic: str = "", shown: int = SHOWN) -> str:
    """이번 주제와 겹치는 예시는 빼고, 남은 것 중에서 골라 보여준다.

    모델은 예시를 모방하지 않고 베낀다. 주제가 같으면 전제와 오치를 그대로
    가져온다. "헬스장 등록" 으로 돌렸더니 예시의 "회원권이 대신 운동한다" 가
    전제도 오치도 그대로 나왔다.

    전부 빠지면 그때는 넣는다. 예시 없는 프롬프트가 베끼는 것보다 나쁘다.

    다 넣지 않고 고르는 이유는 둘이다. 예시가 쌓일수록 프롬프트가 무거워지고,
    매번 같은 예시를 보면 대본이 한 모양으로 굳는다.
    """
    eligible = [ex for ex in EXAMPLES if not overlaps(ex["topic"], topic)] or EXAMPLES
    picked = random.sample(eligible, shown) if len(eligible) > shown else eligible
    return "\n\n".join(
        f"[예시 {i}] 주제: {ex['topic']} / 전제: {ex['premise']}\n{ex['script']}"
        for i, ex in enumerate(picked, 1)
    )
